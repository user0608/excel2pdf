package excel2pdf

import (
	"errors"
	"log/slog"
)

var ErrExcelOrLibreOfficeNotInstalled = errors.New("neither Microsoft Excel nor LibreOffice is installed on this system")

func convertExcelToPdf(excelFile, pdfFile string) error {
	pibreOfficePath, err := findLibreOfficeBinPath()
	if err != nil {
		return err
	}
	if pibreOfficePath != "" {
		err = convertExcelToPDFWithLibreOffice(excelFile, pdfFile)
		if err == nil {
			slog.Info("PDF successfully generated by LibreOffice", "file", pdfFile)
		}
		return err
	}

	ok, err := isExcelInstalled()
	if err != nil {
		return err
	}
	if ok {
		err = convertExcelToPDFWithExcel(excelFile, pdfFile)
		if err == nil {
			slog.Info("PDF successfully generated by Microsof Excel", "file", pdfFile)
		}
		return err
	}
	return ErrExcelOrLibreOfficeNotInstalled
}
